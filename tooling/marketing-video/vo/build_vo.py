"""Place the voiceover lines on the film's timeline and export what the scene and the mixer need.

  vo/plan.json  voice, speed, film length T and each line's start (s)
  ->  audio/vo.wav          mono 48 kHz float, the dry VO track
      explainer-vo.js       window.VO: per line t0/t1/text and its words with times (from faster-whisper)
      explainer.srt         captions for YouTube, from the script text, split on clause breaks
Word times come from transcribing each line (cached by the line's audio hash), so the scene can sync to words.
"""

import difflib
import hashlib
import json
import os
import re
import sys
import numpy as np
import soundfile as sf
from scipy.signal import resample_poly, butter, sosfilt

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
plan = json.load(open(os.path.join(HERE, "plan.json")))
script = {i: t for i, t, *_ in json.load(open(os.path.join(HERE, "script.json")))}
LD = os.path.join(HERE, "lines", f"{plan['voice']}-{plan['speed']:g}")
SR = 48000
T = plan["T"]

model = None


def words_of(path):
    """faster-whisper word timings for one line, cached by audio hash."""
    global model
    h = hashlib.sha1(open(path, "rb").read()).hexdigest()[:16]
    cp = os.path.join(HERE, "cache", h + ".json")
    if os.path.exists(cp):
        return json.load(open(cp))
    if model is None:
        from faster_whisper import WhisperModel

        model = WhisperModel(
            os.path.join(os.environ.get("VO_MODELS", os.path.join(HERE, "models")), "whisper-small.en"),
            device="cpu",
            compute_type="int8",
        )
    segs, _ = model.transcribe(path, language="en", beam_size=5, word_timestamps=True, condition_on_previous_text=False)
    w = [[x.word.strip(), round(x.start, 3), round(x.end, 3)] for s in segs for x in s.words]
    json.dump(w, open(cp, "w"))
    return w


def norm(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


track = np.zeros(int(round(T * SR)))
hp = butter(2, 70, "hp", fs=SR, output="sos")
VO = {"T": T, "lines": {}}
for lid, t0 in plan["starts"].items():
    p = os.path.join(LD, lid + ".wav")
    a, sr = sf.read(p, dtype="float64")
    a = resample_poly(a, SR, sr) if sr != SR else a
    a = sosfilt(hp, a)
    i0 = int(round(t0 * SR))
    if i0 + len(a) > len(track):
        sys.exit(f"{lid} runs past T ({t0 + len(a) / SR:.2f} > {T})")
    track[i0 : i0 + len(a)] += a
    asr = words_of(p)
    # map the script's words onto the transcript's (numbers and names can differ: "fifty" vs "50")
    sw = script[lid].split()
    sm = difflib.SequenceMatcher(a=[norm(x) for x in sw], b=[norm(x[0]) for x in asr], autojunk=False)
    times = [None] * len(sw)
    for blk in sm.get_matching_blocks():
        for k in range(blk.size):
            times[blk.a + k] = asr[blk.b + k][1:]
    # unmatched script words: interpolate between neighbours
    known = [i for i, x in enumerate(times) if x]
    for i in range(len(sw)):
        if times[i] is None:
            prev = max([k for k in known if k < i], default=None)
            nxt = min([k for k in known if k > i], default=None)
            a0 = times[prev][1] if prev is not None else 0.0
            a1 = times[nxt][0] if nxt is not None else len(a) / SR
            lo = prev if prev is not None else -1
            hi = nxt if nxt is not None else len(sw)
            f0 = (i - lo - 1) / (hi - lo - 1)
            f1 = (i - lo) / (hi - lo - 1)
            times[i] = [a0 + (a1 - a0) * f0, a0 + (a1 - a0) * f1]
    dur = len(a) / SR
    VO["lines"][lid] = {
        "t0": round(t0, 3),
        "t1": round(t0 + dur, 3),
        "text": script[lid],
        "words": [[w, round(t0 + x[0], 3), round(t0 + x[1], 3)] for w, x in zip(sw, times)],
    }
    print(f"{lid:4s} {t0:6.2f} → {t0 + dur:6.2f}  {script[lid]}")
    unmatched = len(sw) - sum(b.size for b in sm.get_matching_blocks())
    if unmatched:
        print(f"      {unmatched} word(s) placed by interpolation")

starts = sorted((v["t0"], v["t1"], k) for k, v in VO["lines"].items())
for (a0, a1, k), (b0, b1, k2) in zip(starts, starts[1:]):
    if b0 < a1 + 0.15:
        sys.exit(f"{k2} starts {b0:.2f}, only {b0 - a1:.2f}s after {k} ends")
sf.write(os.path.join(ROOT, "audio", "vo.wav"), track.astype(np.float32), SR, subtype="FLOAT")
open(os.path.join(ROOT, "explainer-vo.js"), "w").write(
    "// generated by vo/build_vo.py: the voiceover's lines and word times (s)\nwindow.VO = "
    + json.dumps(VO, separators=(",", ":"))
    + ";\n"
)


# captions: a cue per sentence, a long sentence split at a colon or else its most central comma; two balanced lines
# of at most 42 characters, broken after punctuation or before a conjunction rather than after a little word;
# numbers and the URL written the way people read them
SHOWN = [
    ("twenty-seven", "27"),
    ("eighty-four dollars", "$84"),
    ("fifty milliseconds", "50 milliseconds"),
    ("forty dollars", "$40"),
    ("Macro is forty,", "Macro is $40,"),
    ("macro dot com", "macro.com"),
]
WEAK = {"a", "an", "and", "at", "in", "is", "of", "or", "the", "to", "with"}
LEAD = {"and", "or", "if", "from", "to", "with", "in", "next"}  # good words to start a second line on


def fmt(t):
    ms = int(round(t * 1000))
    return f"{ms // 3600000:02d}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d},{ms % 1000:03d}"


def shown(s):
    for a, b in SHOWN:
        s = s.replace(a, b)
    return s


def wrap(s, n=42):
    if len(s) <= n:
        return s
    cuts = [i for i, c in enumerate(s) if c == " "]
    cuts = [i for i in cuts if max(i, len(s) - i - 1) <= n] or cuts

    # balance the two lines, preferring to break after a comma and not after a little word
    def cost(i):
        after, before = s[:i].split()[-1], s[i + 1 :].split()[0]
        return (
            max(i, len(s) - i - 1)
            - (10 if s[i - 1] in ",:" else 0)
            + (6 if after in WEAK else 0)
            - (5 if before in LEAD else 0)
        )

    i = min(cuts, key=cost)
    return s[:i] + "\n" + s[i + 1 :]


def text_len(g):
    return len(shown(" ".join(x[0] for x in g)))


cues = []
for k, v in sorted(VO["lines"].items(), key=lambda kv: kv[1]["t0"]):
    W = v["words"]
    sentences, cur = [], []
    for w in W:
        cur.append(w)
        if re.search(r"[.?!]$", w[0]) and w is not W[-1]:
            sentences.append(cur)
            cur = []
    sentences.append(cur)
    for g in sentences:
        parts = [g]
        if text_len(g) > 80:
            commas = [i for i in range(2, len(g) - 2) if g[i][0].endswith(":")]
            commas = commas or [i for i in range(2, len(g) - 2) if g[i][0].endswith(",")]
            if commas:
                i = min(commas, key=lambda i: abs(text_len(g[: i + 1]) - text_len(g) / 2))
                parts = [g[: i + 1], g[i + 1 :]]
        for q in parts:
            cues.append((q[0][1], q[-1][2] + 0.25, shown(" ".join(x[0] for x in q))))
cues = [(a, min(b, cues[i + 1][0] - 0.05) if i + 1 < len(cues) else b, s) for i, (a, b, s) in enumerate(cues)]
open(os.path.join(ROOT, "explainer.srt"), "w").write(
    "\n".join(f"{i + 1}\n{fmt(a)} --> {fmt(b)}\n{wrap(s)}\n" for i, (a, b, s) in enumerate(cues))
)
print(f"vo.wav {T}s, {len(cues)} captions")
